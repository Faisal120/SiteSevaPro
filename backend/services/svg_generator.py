from services.layout_engine import generate_layout
from html import escape
from services.cad_symbols import (
door,
window,
bed,
sofa
)

def generate_floor_svg(data):

    rooms = generate_layout(data)

    plot_width = data.get("plot_width", 30)
    plot_length = data.get("plot_length", 50)

    facing = data.get("facing", "East")
    bedrooms = data.get("bedrooms", 2)
    bathrooms = data.get("bathrooms", 2)

    company_name = escape(
        str(data.get("company_name", ""))
    )

    client_name = escape(
        str(data.get("client_name", ""))
    )

    project_name = escape(
        str(data.get("project_name", ""))
    )

    svg = f"""
    <svg xmlns="http://www.w3.org/2000/svg"
        width="1400"
        height="1000">

    <rect
        x="0"
        y="0"
        width="1400"
        height="1000"
        fill="white"/>

    <text
        x="420"
        y="40"
        font-size="28"
        font-weight="bold">
        {company_name}
    </text>

    <text
        x="40"
        y="80"
        font-size="18">
        Plot Size : {plot_width} x {plot_length} ft
    </text>

    <text
        x="40"
        y="110"
        font-size="18">
        Facing : {facing}
    </text>

    <text
        x="40"
        y="140"
        font-size="18">
        Bedrooms : {bedrooms}
    </text>

    <text
        x="40"
        y="170"
        font-size="18">
        Bathrooms : {bathrooms}
    </text>

    <text
        x="40"
        y="210"
        font-size="18">
        Project : {project_name}
    </text>

    <text
        x="40"
        y="235"
        font-size="18">
        Client : {client_name}
    </text>

    <rect
        x="30"
        y="220"
        width="1200"
        height="700"
        fill="none"
        stroke="black"
        stroke-width="5"
    />
    """

    for room in rooms:

        if room.get("furniture") == "BED":
            svg += bed(
                room["x"] + 20,
                room["y"] + 40
            )

        if room.get("furniture") == "SOFA":
            svg += sofa(
                room["x"] + 20,
                room["y"] + 50
            )

        svg += door(
            room["x"] + room["w"] - 45,
            room["y"] + room["h"] - 5
        )

        svg += window(
            room["x"] + 40,
            room["y"]
        )

        svg += f"""
        <rect
            x="{room['x']}"
            y="{room['y']}"
            width="{room['w']}"
            height="{room['h']}"
            fill="#ffffff"
            stroke="black"
            stroke-width="3"
        />

        <text
            x="{room['x'] + 20}"
            y="{room['y'] + 35}"
            font-size="18"
            font-weight="bold">
            {room['name']}
        </text>

        <text
            x="{room['x'] + 20}"
            y="{room['y'] + 60}"
            font-size="12">
            {round(room['w']/15)} x {round(room['h']/15)} ft
        </text>
        """

    svg += """
    <line
        x1="1280"
        y1="250"
        x2="1280"
        y2="180"
        stroke="red"
        stroke-width="4"/>

    <polygon
        points="1280,160 1270,180 1290,180"
        fill="red"/>

    <text
        x="1268"
        y="150"
        font-size="18"
        font-weight="bold">
        N
    </text>

    <text
        x="40"
        y="960"
        font-size="16">
        Generated by SiteSeva Pro
    </text>
    """

    svg += "</svg>"

    return svg