import 'package:flutter/material.dart';
import 'package:flutter_animate/flutter_animate.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../../../../core/theme/app_theme.dart';
import '../../../../core/widgets/app_ui.dart';
import '../../models/assistant_models.dart';
import '../../providers/assistant_provider.dart';

class AssistantScreen extends ConsumerStatefulWidget {
  const AssistantScreen({super.key});

  @override
  ConsumerState<AssistantScreen> createState() => _AssistantScreenState();
}

class _AssistantScreenState extends ConsumerState<AssistantScreen> {
  final _prompt = TextEditingController();

  @override
  void dispose() {
    _prompt.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final state = ref.watch(assistantControllerProvider);
    return AppPage(
      title: 'SiteSeva AI',
      subtitle: 'Construction intelligence grounded in your workspace data.',
      actions: [IconButton(onPressed: () => ref.read(assistantControllerProvider.notifier).load(), icon: const Icon(Icons.refresh_rounded))],
      child: state.when(
        loading: () => ListView(padding: const EdgeInsets.all(20), children: const [AppSkeleton(height: 230), SizedBox(height: 14), AppSkeleton(height: 96)]),
        error: (error, _) => ListView(padding: const EdgeInsets.all(20), children: [EmptyPanel(title: 'AI Assistant unavailable', message: '$error', icon: Icons.auto_awesome_outlined, actionLabel: 'Retry', onAction: () => ref.read(assistantControllerProvider.notifier).load())]),
        data: _body,
      ),
    );
  }

  Widget _body(AssistantWorkspaceData data) => ListView(
    padding: const EdgeInsets.fromLTRB(20, 4, 20, 120),
    physics: const AlwaysScrollableScrollPhysics(parent: BouncingScrollPhysics()),
    children: [
      _Hero().animate().fadeIn(duration: 280.ms).slideY(begin: .05, end: 0),
      const SizedBox(height: 16),
      if (!data.apiAvailable)
        EmptyPanel(title: 'Assistant backend pending', message: data.apiMessage ?? 'The service is not available.', icon: Icons.hub_outlined)
      else ...[
        if (data.messages.isEmpty)
          const EmptyPanel(title: 'No conversation yet', message: 'Ask about a site, schedule, materials, estimates or payment risk.', icon: Icons.forum_outlined)
        else
          ...data.messages.map((message) => _MessageBubble(message: message)),
        const SizedBox(height: 16),
        _Composer(controller: _prompt),
      ],
    ],
  );
}

class _Hero extends StatelessWidget {
  @override
  Widget build(BuildContext context) => Container(
    padding: const EdgeInsets.all(22),
    decoration: BoxDecoration(borderRadius: BorderRadius.circular(30), gradient: const LinearGradient(colors: [Color(0xFF071323), Color(0xFF104488), Color(0xFF2563EB)])),
    child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
      Container(width: 48, height: 48, decoration: BoxDecoration(color: Colors.white.withValues(alpha: .14), borderRadius: BorderRadius.circular(17)), child: const Icon(Icons.auto_awesome_rounded, color: Colors.white)),
      const SizedBox(height: 22),
      Text('Ask your construction workspace.', style: Theme.of(context).textTheme.headlineSmall?.copyWith(color: Colors.white, fontWeight: FontWeight.w800)),
      const SizedBox(height: 7),
      Text('Answers must be generated by the authenticated SiteSeva AI backend, never from local placeholder data.', style: Theme.of(context).textTheme.bodySmall?.copyWith(color: const Color(0xFFCBE0FF), height: 1.45)),
    ]),
  );
}

class _MessageBubble extends StatelessWidget {
  const _MessageBubble({required this.message});
  final AssistantMessage message;
  @override
  Widget build(BuildContext context) => Align(
    alignment: message.isAssistant ? Alignment.centerLeft : Alignment.centerRight,
    child: Container(
      margin: const EdgeInsets.only(bottom: 10),
      padding: const EdgeInsets.all(14),
      constraints: const BoxConstraints(maxWidth: 520),
      decoration: BoxDecoration(color: message.isAssistant ? Theme.of(context).cardTheme.color : AppTheme.blue, borderRadius: BorderRadius.circular(20)),
      child: Text(message.content, style: Theme.of(context).textTheme.bodySmall?.copyWith(color: message.isAssistant ? null : Colors.white, height: 1.45)),
    ),
  );
}

class _Composer extends ConsumerWidget {
  const _Composer({required this.controller});
  final TextEditingController controller;
  @override
  Widget build(BuildContext context, WidgetRef ref) => Row(children: [
    Expanded(child: TextField(controller: controller, minLines: 1, maxLines: 4, decoration: const InputDecoration(hintText: 'Ask about a site, risk, estimate or inventory...'))),
    const SizedBox(width: 9),
    IconButton.filled(onPressed: () async {
      try { await ref.read(assistantControllerProvider.notifier).send(AssistantPrompt(controller.text)); controller.clear(); } catch (error) { if (context.mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('$error'))); }
    }, icon: const Icon(Icons.arrow_upward_rounded), style: IconButton.styleFrom(backgroundColor: AppTheme.blue)),
  ]);
}
